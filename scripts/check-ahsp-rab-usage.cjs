const escaped = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const cell = (ref, text) => `<c r="${ref}" t="inlineStr"><is><t>${escaped(text)}</t></is></c>`
function fixture(name, jobs) {
  const zip = new PizZip(fs.readFileSync(root + '/export.xlsx'))
  zip.file('xl/worksheets/sheet1.xml', `<?xml version="1.0"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData><row r="1">${['Kode', 'Uraian', 'Satuan', 'Volume', 'Harga Satuan', 'Jumlah Harga'].map((text, i) => cell(String.fromCharCode(65 + i) + '1', text)).join('')}</row>${jobs.map((job, index) => { const r = index + 2; return `<row r="${r}">${cell('A' + r, job.code)}${cell('B' + r, job.name)}${cell('C' + r, 'Meter Kubik')}${job.noPrice ? '' : `<c r="D${r}"><v>2</v></c><c r="E${r}"><v>${job.price ?? 1200}</v></c><c r="F${r}"><v>${(job.price ?? 1200) * 2}</v></c>`}</row>` }).join('')}</sheetData></worksheet>`)
  const filename = `${root}/${name}.xlsx`
  fs.writeFileSync(filename, zip.generate({ type: 'nodebuffer' }))
  return filename
}
