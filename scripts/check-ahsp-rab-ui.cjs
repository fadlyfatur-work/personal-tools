/* eslint-disable @typescript-eslint/no-require-imports -- Standalone CommonJS browser check. */
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const ts = require('typescript')
const PizZip = require('pizzip')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'))

const origin = process.env.RAB_ORIGIN || 'http://localhost:3000'
const sampleDir = process.env.RAB_SAMPLES || 'C:/Users/User/Downloads/PEMERIKSAAN'
const compile = file => ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText
async function main() {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const results = []
  try {
    await page.goto(origin + '/ahsp/rab')
    await page.getByRole('heading', { name: 'Pencocokan RAB', exact: true }).waitFor()
    await page.addScriptTag({ content: fs.readFileSync('node_modules/pizzip/dist/pizzip.min.js', 'utf8') })
    await page.evaluate(({ core, rab, excel }) => {
      const execute = (code, imports) => { const exports = {}; new Function('require', 'exports', code)(name => imports[name], exports); return exports }
      const c = execute(core, {})
      const r = execute(rab, { './ahsp': c })
      window.rabTest = { ...r, ...execute(excel, { './ahspRab': r, pizzip: window.PizZip }) }
    }, { core: compile('lib/ahsp.ts'), rab: compile('lib/ahspRab.ts'), excel: compile('lib/ahspRabExcel.ts') })
    const samples = [['DKH KALTENG.xlsx', 5], ['DKH JABAR.xlsx', 24], ['DKH JATIM.xlsx', 23], ['DKH BANTEN.xlsx', 43], ['1. Daftar Kuantitas dan Harga - R T.xlsx', 25], ['DKH_Rehabilitasi_Jalan_HOS_Cokroaminoto.xlsx', 51]]
    for (const [name, count] of samples) {
      const file = path.join(sampleDir, name)
      if (!fs.existsSync(file)) continue
      const inspected = await page.evaluate(bytes => {
        const workbook = window.rabTest.readRabWorkbook(new Uint8Array(bytes))
        const sheet = workbook[0], rows = window.rabTest.extractRabRows(sheet, sheet.mapping)
        return { mapping: sheet.mapping, count: rows.filter(r => !r.excluded).length, unreviewed: rows.filter(r => !r.excluded && !r.reviewed).length, lostDescriptions: rows.filter(r => r.name === 'Uraian belum terbaca').length, itemRows: rows.filter(r => !r.excluded).map(r => r.row), missingTotals: rows.filter(r => !r.excluded && r.total === null).length }
      }, [...fs.readFileSync(file)])
      console.log(name, { count: inspected.count, unreviewed: inspected.unreviewed, mapping: inspected.mapping })
      assert.equal(inspected.count, count, name + ' item count')
      assert.equal(inspected.lostDescriptions, 0, name + ' descriptions retained')
      if (name.includes('KALTENG')) { assert.equal(inspected.unreviewed, 5); assert.deepEqual(inspected.itemRows, [8, 9, 10, 12, 13]); assert.equal(inspected.missingTotals, 0) }
      if (name.includes('JATIM')) assert.equal(inspected.mapping.name, 'D')
      results.push(name)
    }
    const catalogResponse = await page.request.get(origin + '/api/ahsp/rab')
    console.log('catalog status', catalogResponse.status())
    if (!catalogResponse.ok()) throw new Error('Live AHSP catalog unavailable: ' + await catalogResponse.text())
    const catalog = await catalogResponse.json()
    assert.ok(catalog.items.length > 1000)
    console.log('Live catalog versions', catalog.items.length)
    await page.getByLabel('Dokumen Excel').setInputFiles(path.join(sampleDir, 'DKH KALTENG.xlsx'))
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).waitFor()
    const mapping = page.getByRole('group', { name: 'Table 7', exact: true })
    await mapping.getByRole('button', { name: 'Ubah kolom Volume', exact: true }).click()
    await page.getByRole('dialog', { name: 'Pilih kolom Volume', exact: true }).getByRole('button', { name: /^Gunakan kolom F:/ }).click()
    assert.ok((await mapping.getByRole('button', { name: 'Ubah kolom Harga Satuan (Rupiah)', exact: true }).innerText()).includes('Kolom D'))
    await mapping.getByRole('button', { name: 'Urungkan', exact: true }).click()
    assert.ok((await mapping.getByRole('button', { name: 'Ubah kolom Volume', exact: true }).innerText()).includes('Kolom D'))
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).click()
    await page.getByText(/^Pencocokan selesai\. Periksa/).waitFor({ timeout: 60000 })
    assert.ok((await page.getByRole('region', { name: 'Rekapitulasi pencocokan' }).innerText()).includes('5 item menunggu'))
    await page.getByRole('button', { name: 'Periksa data', exact: true }).first().click()
    const edit = page.getByRole('dialog', { name: 'Periksa pembacaan item' })
    const originalVolume = await edit.getByLabel('Volume', { exact: true }).inputValue()
    await edit.getByLabel('Volume', { exact: true }).fill('999')
    await edit.getByRole('button', { name: 'Pulihkan isian dari sumber', exact: true }).click()
    assert.equal(await edit.getByLabel('Volume', { exact: true }).inputValue(), originalVolume)
    await edit.getByLabel('Saya telah memeriksa', { exact: false }).check()
    await edit.getByRole('button', { name: 'Simpan pemeriksaan', exact: true }).click()
    await page.getByRole('button', { name: 'Cari pasangan', exact: true }).first().click()
    const search = page.getByRole('dialog', { name: 'Cari pasangan pekerjaan' })
    await search.getByLabel('Metode', { exact: true }).selectOption('like')
    await search.getByLabel('Kata kunci', { exact: true }).fill('mobilisasi')
    await search.getByRole('button', { name: 'Cari rekomendasi', exact: true }).click()
    await search.getByLabel('Metode', { exact: true }).selectOption('phrases')
    await search.getByLabel('Kata kunci', { exact: true }).fill('"Mobilisasi" "Demobilisasi"')
    await search.getByRole('button', { name: 'Cari rekomendasi', exact: true }).click()
    await search.getByRole('button', { name: 'Gunakan', exact: true }).first().click()
    const confirm = page.getByRole('dialog', { name: 'Gunakan pasangan ini?' })
    await confirm.waitFor()
    if (await confirm.getByLabel('Penyelesaian perbedaan dan alasan memilih', { exact: true }).count()) await confirm.getByLabel('Penyelesaian perbedaan dan alasan memilih', { exact: true }).fill('Pemeriksaan UI: pasangan dipilih manual setelah membandingkan sumber.')
    await confirm.getByRole('button', { name: 'Batalkan', exact: true }).click()
    assert.equal(await search.isVisible(), true)
    await search.getByRole('button', { name: 'Gunakan', exact: true }).first().click()
    if (await confirm.getByLabel('Penyelesaian perbedaan dan alasan memilih', { exact: true }).count()) await confirm.getByLabel('Penyelesaian perbedaan dan alasan memilih', { exact: true }).fill('Pemeriksaan UI: pasangan dipilih manual setelah membandingkan sumber.')
    await confirm.getByRole('button', { name: 'Konfirmasi dan gunakan', exact: true }).click()
    await page.getByRole('button', { name: /^Cocok \(/ }).click()
    await page.getByText('Cocok · manual', { exact: true }).waitFor()
    const downloaded = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Unduh Excel', exact: true }).click()
    const download = await downloaded
    fs.mkdirSync('.next/rab-tests', { recursive: true })
    await download.saveAs('.next/rab-tests/ui-export.xlsx')
    await page.getByRole('button', { name: 'Batalkan pasangan', exact: true }).click()
    await page.getByRole('button', { name: /^Tidak cocok/ }).click()
    await page.getByRole('button', { name: 'Periksa data', exact: true }).first().click()
    await edit.getByLabel('Kecualikan dari daftar pekerjaan', { exact: true }).check()
    await edit.getByLabel('Alasan pengecualian', { exact: true }).fill('Pemeriksaan UI: dikecualikan sementara.')
    await edit.getByRole('button', { name: 'Simpan pemeriksaan', exact: true }).click()
    await page.getByRole('button', { name: /Periksa 1 baris dikecualikan/ }).click()
    await page.getByRole('button', { name: 'Ubah pengecualian', exact: true }).click()
    await edit.getByLabel('Kecualikan dari daftar pekerjaan', { exact: true }).uncheck()
    await edit.getByRole('button', { name: 'Simpan pemeriksaan', exact: true }).click()
    await page.getByRole('button', { name: 'Periksa data', exact: true }).first().click()
    await page.keyboard.press('Escape')
    assert.equal(await edit.isVisible(), false)
    for (const width of [1440, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 900 })
      for (const theme of ['light', 'dark', 'system']) {
        await page.getByLabel('Tampilan', { exact: true }).selectOption(theme)
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `No outer overflow ${width} ${theme}`)
      }
    }
    await page.screenshot({ path: '.next/rab-tests/mobile.png', fullPage: true })
    page.on('dialog', dialog => dialog.accept())
    const fixture = new PizZip(fs.readFileSync('.next/rab-tests/ui-export.xlsx'))
    for (let sheetIndex = 1; sheetIndex <= 5; sheetIndex++) {
      const count = sheetIndex === 1 ? 1003 : 3
      const cell = (address, text) => `<c r="${address}" t="inlineStr"><is><t>${text}</t></is></c>`
      fixture.file(`xl/worksheets/sheet${sheetIndex}.xml`, `<?xml version="1.0"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData><row r="1">${cell('A1', 'Uraian')}${cell('B1', 'Satuan')}${cell('C1', 'Volume')}${cell('D1', 'Harga Satuan')}${cell('E1', 'Jumlah Harga')}</row>${Array.from({ length: count - 1 }, (_, i) => { const r = i + 2; return `<row r="${r}">${cell('A' + r, i % 2 ? 'Mobilisasi' : 'Galian Biasa')}${cell('B' + r, i % 2 ? 'LS' : 'm3')}<c r="C${r}"><v>1</v></c><c r="D${r}"><v>10</v></c><c r="E${r}"><v>10</v></c></row>` }).join('')}</sheetData></worksheet>`)
    }
    fs.writeFileSync('.next/rab-tests/limits.xlsx', fixture.generate({ type: 'nodebuffer' }))
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Ganti file', exact: true }).click()
    await page.getByLabel('Dokumen Excel').setInputFiles('.next/rab-tests/limits.xlsx')
    const choices = page.getByRole('group', { name: /^Sheet yang diproses/ }).getByRole('checkbox')
    await choices.nth(1).check(); await choices.nth(2).check()
    assert.equal(await choices.nth(3).isDisabled(), true, 'Only three sheets selectable')
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).click()
    await page.getByRole('alert').getByText('Konfirmasikan batas 1.000 baris atau batalkan proses.', { exact: true }).waitFor()
    await page.getByLabel('Saya memahami dan menyetujui cakupan terbatas ini.', { exact: true }).check()
    await page.getByLabel('Saya sudah memeriksa dan tetap memakai sheet yang dipilih.', { exact: true }).check()
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).click()
    await page.getByText(/^Pencocokan selesai\. Periksa/).waitFor({ timeout: 60000 })
    const summary = await page.getByRole('region', { name: 'Rekapitulasi pencocokan' }).innerText()
    assert.ok(summary.includes('1.003') || summary.includes('1003'), '999 items first sheet and 2 each from other sheets')
    assert.ok(summary.includes('Cakupan terbatas'))
    await page.getByRole('button', { name: /^Tidak cocok \(/ }).click()
    await page.getByRole('button', { name: 'Berikutnya', exact: true }).click()
    await page.getByText(/Halaman 2 \//).waitFor()
    const limitDownload = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Unduh Excel', exact: true }).click()
    await (await limitDownload).saveAs('.next/rab-tests/limits-export.xlsx')
    const exported = new PizZip(fs.readFileSync('.next/rab-tests/limits-export.xlsx'))
    const exportedItems = [2, 3, 4].reduce((sum, index) => sum + (exported.file(`xl/worksheets/sheet${index}.xml`).asText().match(/<row /g) || []).length - 1, 0)
    assert.equal(exportedItems, 1003, 'All examined items exported, not only visible page')
    assert.ok(exported.file('xl/worksheets/sheet1.xml').asText().includes('TERBATAS'))
    const normalize = text => text.normalize('NFKC').toLowerCase().replace(/\s+/g, ' ').trim()
    const primaryNames = new Set(catalog.items.filter(c => c.regulation !== 'SE 182/2025').map(c => normalize(c.name)))
    const archived = catalog.items.find(c => c.regulation === 'SE 182/2025' && c.unit && c.unit !== '-' && !primaryNames.has(normalize(c.name)))
    assert.ok(archived, 'Live catalog has an archive-only work item to verify separation')
    const escaped = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    const c = (address, text) => `<c r="${address}" t="inlineStr"><is><t>${escaped(text)}</t></is></c>`
    fixture.file('xl/worksheets/sheet1.xml', `<?xml version="1.0"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData><row r="1">${c('A1', 'Uraian')}${c('B1', 'Satuan')}${c('C1', 'Volume')}${c('D1', 'Harga Satuan')}${c('E1', 'Jumlah Harga')}</row><row r="2">${c('A2', archived.name)}${c('B2', archived.unit)}<c r="C2"><v>1</v></c><c r="D2"><v>10</v></c><c r="E2"><v>10</v></c></row></sheetData></worksheet>`)
    fs.writeFileSync('.next/rab-tests/archive.xlsx', fixture.generate({ type: 'nodebuffer' }))
    await page.goto(origin + '/ahsp/rab')
    await page.getByLabel('Dokumen Excel').setInputFiles('.next/rab-tests/archive.xlsx')
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).click()
    await page.getByText(/^Pencocokan selesai\. Periksa/).waitFor({ timeout: 60000 })
    assert.ok((await page.locator('dl').first().locator('div').nth(1).innerText()).includes('0 (0%)'))
    assert.ok((await page.locator('dl').first().locator('div').nth(2).innerText()).includes('1 (100%)'))
    await page.getByRole('button', { name: /^Cocok \(/ }).click()
    await page.getByRole('heading', { name: 'Regulasi tambahan · terpisah dari persentase utama', exact: true }).waitFor()
    assert.equal(await page.getByRole('heading', { name: 'Regulasi utama · SE 47/2026 dan Permen 08/2023', exact: true }).count(), 0)
    await page.goto(origin + '/ahsp/rab')
    await page.route('**/api/ahsp/rab', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Katalog gagal dimuat untuk uji pemulihan.' }) }))
    await page.getByLabel('Dokumen Excel').setInputFiles(path.join(sampleDir, 'DKH JATIM.xlsx'))
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).click()
    await page.getByRole('alert').getByText('Katalog gagal dimuat untuk uji pemulihan.', { exact: true }).waitFor()
    assert.ok((await page.getByRole('region', { name: 'Rekapitulasi pencocokan' }).innerText()).includes('23'))
    await page.unroute('**/api/ahsp/rab')
    await page.getByRole('button', { name: 'Lanjutkan pencocokan', exact: true }).click()
    await page.getByText(/^Pencocokan selesai\. Periksa/).waitFor({ timeout: 60000 })
    await page.goto(origin + '/ahsp')
    await page.getByRole('link', { name: 'Pencocokan RAB', exact: true }).click()
    await page.waitForURL('**/ahsp/rab')
    assert.deepEqual(errors, [])
    console.log('PASS: real samples, live catalog, upload, both search methods, data confirmation, nested modal cancel/confirm, recap changes, undo, exclusion/restore, Escape, responsive themes, 3-sheet cap, 1000-row consent, duplicate notice, pagination, complete XLSX export, API failure/retry and catalog navigation.', results)
  } catch (error) {
    console.log('PAGE ERRORS', errors)
    console.log((await page.locator('body').innerText()).slice(-8000))
    fs.mkdirSync('.next/rab-tests', { recursive: true })
    await page.screenshot({ path: '.next/rab-tests/failure.png', fullPage: true })
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
