const assert = require('node:assert/strict')
const { setMode } = require('./ahsp-appearance-browser.cjs')
const fs = require('node:fs')
const path = require('node:path')
const { createRequire } = require('node:module')
const PizZip = require('pizzip')
const runtime = createRequire(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/package.json'))
const { chromium } = runtime('playwright')
const root = '.next/rab-tests'
const origin = 'http://localhost:3000'
fs.mkdirSync(root, { recursive: true })
const uuid = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`
const a = { id: uuid(1), code: 'A.01', name: 'Beton struktur mutu fc 20 MPa', unit: 'm3', regulation: 'SE 47/2026', regulation_status: '' }
const b = { ...a, id: uuid(2), code: 'B.01', name: 'Pekerjaan arsip terverifikasi', regulation: 'SE 182/2025', regulation_status: 'Digantikan oleh SE 47/2026' }
const escape = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')
const textCell = (ref, text) => `<c r="${ref}" t="inlineStr"><is><t>${escape(text)}</t></is></c>`
const sources = [
  [a.code, a.name, 'm3', 2, 10.125, 20.25], [a.code, a.name, 'Meter Kubik', 3, 12.555, 37.665],
  [b.code, b.name, 'm3', 1, 100, 100],
  ['X.01', 'Pekerjaan belum terdaftar', 'm3', 2, 15, 30], ['X.01', 'Pekerjaan belum terdaftar', 'm2', 4, 95762945278.97902, 95762945278.97902],
]
const fixture = new PizZip()
fixture.file('[Content_Types].xml', '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>')
fixture.file('_rels/.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>')
fixture.file('xl/workbook.xml', '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="RAB" sheetId="1" r:id="rId1"/></sheets></workbook>')
fixture.file('xl/_rels/workbook.xml.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>')
fixture.file('xl/worksheets/sheet1.xml', `<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData><row r="1">${['Kode', 'Uraian', 'Satuan', 'Volume', 'Harga Satuan', 'Jumlah Harga'].map((value, i) => textCell(String.fromCharCode(65+i)+'1', value)).join('')}</row>${sources.map((values, index) => `<row r="${index+2}">${values.map((value, col) => typeof value === 'number' ? `<c r="${String.fromCharCode(65+col)}${index+2}"><v>${value}</v></c>` : textCell(String.fromCharCode(65+col)+(index+2), value)).join('')}</row>`).join('')}</sheetData></worksheet>`)
fs.writeFileSync(root + '/sessions-source.xlsx', fixture.generate({ type: 'nodebuffer' }))
async function main() {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  await context.route('**/api/ahsp/rab', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ items: [a, b], loadedAt: new Date().toISOString() }) }))
  await context.route('**/api/ahsp/rab/components', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ analyses: [a,b].map(item => ({ item, analysis: item, status: 'extracted', identity_scope: JSON.stringify([item.regulation,'BM','test']), components: [{ group: 'tenaga', name: 'Pekerja', code: 'L01', unit: 'jam' }], excluded_components: 0, note: '' })) }) }))
  let page = await context.newPage()
  const errors = []
  const bind = page => { page.on('dialog', dialog => dialog.accept()); page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(15000) }
  bind(page)
  try {
    await page.goto(origin + '/ahsp/rab')
    for (const theme of ['light','dark']) {
      await setMode(page,theme)
      await page.screenshot({path:`${root}/swiss-empty-${theme}.png`,fullPage:true})
      const palette=await page.locator('main').evaluate(element=>{const s=getComputedStyle(element);return{background:s.backgroundColor,color:s.color,action:s.getPropertyValue('--action').trim(),accent:s.getPropertyValue('--accent').trim()}})
      assert.equal(palette.action,'#db0000')
      assert.equal(palette.background,theme==='light'?'rgb(255, 255, 255)':'rgb(0, 0, 0)')
      const rgb=value=>value.match(/[\d.]+/g).slice(0,3).map(Number)
      const luminance=rgb=>rgb.map(value=>{const n=value/255;return n<=.04045?n/12.92:((n+.055)/1.055)**2.4}).reduce((sum,value,index)=>sum+value*[.2126,.7152,.0722][index],0)
      const contrast=(a,b)=>(Math.max(luminance(a),luminance(b))+.05)/(Math.min(luminance(a),luminance(b))+.05)
      assert.ok(contrast(rgb(palette.color),rgb(palette.background))>=4.5)
      const backColor=await page.getByRole('link',{name:'Kembali ke katalog AHSP',exact:true}).evaluate(element=>getComputedStyle(element).color)
      assert.ok(contrast(rgb(backColor),rgb(palette.background))>=4.5,'Back navigation text remains readable in both themes')
      assert.ok(contrast([219,0,0],[255,255,255])>=4.5,'Primary action contrast stays accessible in both themes')
      assert.ok(contrast(theme==='light'?[219,0,0]:[255,0,0],theme==='light'?[255,255,255]:[10,10,10])>=4.5,'Accent text has readable contrast on its card')
    }
    await setMode(page,'light')
    await page.getByLabel('Dokumen Excel').setInputFiles(root + '/sessions-source.xlsx')
    await page.screenshot({path:root+'/swiss-mapping.png',fullPage:true})
    await page.getByRole('button', { name: 'Baca dan cocokkan', exact: true }).click()
    await page.getByText(/^Pencocokan selesai\. Periksa/).waitFor()
    const recap = () => page.getByRole('region', { name: 'Rekapitulasi pencocokan', exact: true })
    assert.ok((await recap().innerText()).includes('60,00%'))
    assert.equal((await recap().innerText()).includes('item tanpa total'), false)
    assert.equal(await page.getByRole('button', { name: '2 kemunculan', exact: true }).count(), 1)
    await page.getByRole('button', { name: 'Tidak ada kecocokan', exact: true }).click()
    await page.getByRole('button', { name: 'Periksa kembali', exact: true }).waitFor()
    assert.ok((await page.getByRole('status').allTextContents()).join(' ').includes('2 kemunculan'))
    await page.getByRole('button', { name: 'Periksa kembali', exact: true }).click()
    await page.getByRole('button', { name: 'Cari pasangan', exact: true }).click()
    const search = page.getByRole('dialog', { name: 'Cari pasangan pekerjaan', exact: true })
    await search.getByLabel('Metode', { exact: true }).selectOption('like')
    await search.getByLabel('Kata kunci', { exact: true }).fill(a.name)
    await search.getByRole('button', { name: 'Cari rekomendasi', exact: true }).click()
    await search.getByRole('button', { name: 'Gunakan', exact: true }).click()
    const confirm = page.getByRole('dialog', { name: 'Gunakan pasangan ini?', exact: true })
    assert.ok((await confirm.innerText()).includes('2 kemunculan'))
    assert.ok((await confirm.innerText()).includes('m2 / m3'), 'Unit difference of a nonrepresentative occurrence is disclosed')
    await confirm.getByRole('button', { name: 'Konfirmasi dan gunakan', exact: true }).click()
    assert.ok((await recap().innerText()).includes('100,00%'))
    await page.getByRole('button', { name: /^Cocok \(/ }).click()
    assert.equal(await page.getByRole('button', { name: '2 kemunculan', exact: true }).count(), 2)
    await page.getByRole('button', { name: '2 kemunculan', exact: true }).first().click()
    const occurrences = page.getByRole('dialog', { name: 'Kemunculan item pekerjaan', exact: true })
    await occurrences.getByText(/!B2 · baris 2$/).waitFor()
    assert.ok((await occurrences.innerText()).includes('10,13'))
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Lanjut ke rekap penggunaan komponen', exact: true }).click()
    await page.getByText('Rincian komponen tersedia untuk 5 dari 5 pekerjaan yang cocok (2 AHSP unik).', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Simpan perhitungan', exact: true }).click()
    const save = page.getByRole('dialog', { name: 'Simpan perhitungan', exact: true })
    await save.getByLabel('Nama perhitungan').fill('RAB pengelompokan dan simpan')
    await save.getByRole('button', { name: 'Simpan', exact: true }).click()
    await page.getByText('“RAB pengelompokan dan simpan” tersimpan di browser ini.', { exact: true }).waitFor()
    const stored = await page.evaluate(() => new Promise((resolve, reject) => { const request = indexedDB.open('ahsp-rab',1); request.onsuccess=()=>{ const db=request.result; const read=db.transaction('sessions').objectStore('sessions').getAll(); read.onsuccess=()=>{ resolve(read.result); db.close() }; read.onerror=()=>reject(read.error) } }))
    assert.equal(stored.length, 1)
    assert.equal(stored[0].rows.filter(row => row.status === 'matched').length, 5)
    assert.ok(stored[0].usageReport)
    assert.deepEqual(stored[0].rows.map(row => [row.unit,row.volume,row.price,row.total]), sources.map(row => row.slice(2)))
    await page.close()
    page = await context.newPage(); bind(page)
    await page.goto(origin + '/ahsp/rab')
    await page.getByText('1 perhitungan tersedia', { exact: true }).click()
    await page.getByRole('button', { name: 'Buka', exact: true }).click()
    await page.getByText(/Perhitungan “RAB pengelompokan dan simpan” dibuka/).waitFor()
    await page.getByText('Memeriksa katalog untuk simpanan ini…', { exact: true }).waitFor({ state: 'hidden' })
    assert.ok((await recap().innerText()).includes('100,00%'))
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Selesai dan unduh Excel', exact: true }).click()
    await (await download).saveAs(root + '/sessions-export.xlsx')
    const zip = new PizZip(fs.readFileSync(root + '/sessions-export.xlsx'))
    assert.equal((zip.file('xl/workbook.xml').asText().match(/<sheet /g) || []).length, 9)
    assert.ok(zip.file('xl/workbook.xml').asText().includes('Rekapitulasi MPTK'))
    const final = zip.file('xl/worksheets/sheet6.xml').asText()
    assert.ok(final.includes('<c r="E7" s="4"><v>10.125</v></c>'))
    assert.ok(final.includes('<c r="E8" s="4"><v>12.555</v></c>'))
    assert.ok(final.includes('<c r="H9" s="10"'))
    for (const width of [1440,768,390,320]) for (const theme of ['light','dark']) {
      await page.setViewportSize({width,height:900})
      await setMode(page,theme)
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`${width} ${theme} fits viewport`)
      if (theme === 'light' && [1440,390].includes(width)) await recap().screenshot({path:`${root}/summary-${width}.png`})
      if ([1440,390].includes(width)) await page.screenshot({path:`${root}/swiss-results-${width}-${theme}.png`,fullPage:true})
    }
    await page.getByRole('button',{name:/^Cocok \(/}).click()
    await page.getByRole('button',{name:'Batalkan pasangan',exact:true}).first().click()
    await page.getByRole('button',{name:'Simpan perhitungan',exact:true}).click()
    await page.getByRole('dialog',{name:'Simpan perhitungan',exact:true}).getByRole('button',{name:'Simpan',exact:true}).click()
    await page.getByText('“RAB pengelompokan dan simpan” tersimpan di browser ini.',{exact:true}).waitFor()
    assert.equal(await page.getByText('1 perhitungan tersedia',{exact:true}).count(),1,'Saving updates the current session rather than creating a duplicate')
    if (!(await page.getByRole('region',{name:'Perhitungan tersimpan',exact:true}).locator('details').evaluate(element => element.open))) await page.getByText('1 perhitungan tersedia',{exact:true}).click()
    await context.unroute('**/api/ahsp/rab')
    await context.route('**/api/ahsp/rab', route => route.fulfill({contentType:'application/json',body:JSON.stringify({items:[{...a,name:'Identitas katalog berubah'},b],loadedAt:new Date().toISOString()})}))
    await page.getByRole('button',{name:'Buka',exact:true}).click()
    await page.getByText('Simpanan dibuka. Beberapa identitas katalog berubah dan perlu dipasangkan ulang.',{exact:true}).waitFor()
    assert.ok((await recap().innerText()).includes('20,00%'),'Changed catalog identities require reconciliation rather than silently retaining a match')
    await context.unroute('**/api/ahsp/rab')
    await context.route('**/api/ahsp/rab', route => route.fulfill({status:503,contentType:'application/json',body:'{}'}))
    await page.getByRole('button',{name:'Buka',exact:true}).click()
    await page.getByText('Simpanan dibuka. Katalog belum dapat dimuat; hasil tetap bisa dilihat dan diunduh.',{exact:true}).waitFor()
    assert.ok((await recap().innerText()).includes('60,00%'),'The saved result remains accessible if the catalog is unavailable')
    await page.evaluate(()=>{ window.rabOriginalPut=IDBObjectStore.prototype.put; IDBObjectStore.prototype.put=function(){throw new DOMException('Ruang penyimpanan uji penuh','QuotaExceededError')} })
    await page.getByRole('button',{name:'Simpan perhitungan',exact:true}).click()
    const failedSave=page.getByRole('dialog',{name:'Simpan perhitungan',exact:true})
    await failedSave.getByRole('button',{name:'Simpan',exact:true}).click()
    await failedSave.getByRole('alert').waitFor()
    assert.ok((await recap().innerText()).includes('60,00%'),'A failed save never clears the active calculation')
    await page.evaluate(()=>{ IDBObjectStore.prototype.put=window.rabOriginalPut })
    await failedSave.getByRole('button',{name:'Tutup',exact:true}).click()
    await page.getByRole('button',{name:'Hapus',exact:true}).click()
    await page.getByText('Belum ada perhitungan tersimpan',{exact:true}).waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS: exact grouping, bulk decisions, unit differences, per-occurrence amounts, two-decimal recap, nine-sheet colored export, IndexedDB save/close/reopen/update/delete, responsive themes.')
  } catch(error) { await page.screenshot({ path: root+'/sessions-failure.png', fullPage:true }); throw error }
  finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode=1 })
