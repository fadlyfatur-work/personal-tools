import assert from 'node:assert/strict'
import { prepareMasterList } from './import-ahsp-master-list.mjs'

const sha='a'.repeat(64)
const row={code:'A.1',name:'Pekerjaan contoh',bidang:'Bina Marga',unit:'m3',job_type:'informative',regulasi_se:'SPTJM',overheat_and_profit_percentage:10,row:2}
const prepare=(rows,items=[])=>prepareMasterList(rows,items,{sha256:sha,sourceName:'master.xlsx'})
const result=prepare([row,{...row,row:3}])
assert.equal(result.additions.length,1)
const item=result.additions[0]
assert.equal(item.regulation,'SPTJM')
assert.equal(item.verification_status,'needs_review')
assert.equal(item.analysis_status,'unavailable')
assert.deepEqual(item.components,[])
assert.deepEqual(item.sipasti_rows,[2,3])
assert.equal(item.source_id,null)
assert.equal(item.analysis_target_id,null)
assert.equal(item.analysis_reference,null)
assert.ok(item.verification_notes.some(s=>s.includes('Duplikat')))
assert.equal(prepare([row],[{...item}]).additions.length,0,'Impor ulang tidak menambah versi')
assert.equal(prepare([row],[{...item,regulation:'SE 47/2026',components:[{name:'Tidak boleh disalin'}]}]).additions.length,1,'Versi regulasi berbeda tetap terpisah')
assert.deepEqual(prepare([row],[{...item,regulation:'SE 47/2026',components:[{name:'Tidak boleh disalin'}]}]).additions[0].components,[])
assert.equal(prepare([{...row,unit:''}]).additions[0].unit,'','Satuan kosong tidak direkayasa')
assert.ok(prepare([{...row,unit:''}]).additions[0].verification_notes.some(s=>s.includes('Satuan')))
assert.equal(prepare([{...row,regulasi_se:'null, SPTJM'}]).additions[0].id,item.id)
assert.equal(prepare([{...row,regulasi_se:'-'}]).additions.length,0)
assert.equal(prepare([{...row,regulasi_se:'null'}]).additions.length,0)
assert.equal(prepare([row],[{...item,name:'Nama berbeda'}]).additions.length,0,'Kode yang sudah ada tetapi metadata berbeda perlu tinjauan')
assert.equal(prepare([row],[{...item,code:'OTHER'}]).additions.length,0,'Nama dan satuan sama dengan kode berbeda perlu tinjauan')
assert.equal(prepare([row,{...row,unit:'kg',row:3}]).additions.length,0,'Varian sumber yang berbeda tidak dipilih sewenang-wenang')
assert.throws(()=>prepare([{...row,bidang:''}]),/bidang/i)
assert.throws(()=>prepare([{...row,name:''}]),/nama/i)
const two=prepare([{...row,regulasi_se:'SE 47/2026, SE 182/2025'}])
assert.equal(two.additions.length,2)
assert.equal(new Set(two.additions.map(i=>i.id)).size,2)
assert.deepEqual(prepare([row,{...row,row:3}]),result)
console.log('PASS: identitas lintas regulasi, metadata saja, tanpa komponen/rujukan palsu, nol/kosong, duplikat, konflik, dan idempotensi')
